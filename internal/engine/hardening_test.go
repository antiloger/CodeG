// These tests cover environments beyond a plain single module: broken code,
// generated and test files, embeds, vendoring, workspaces and cgo. All run
// offline.

func offline(t *testing.T) { t.Helper(); t.Setenv("GOPROXY", "off") }

func indexAt(t *testing.T, root, store string, tags ...string) *engine.Result {
	t.Helper()
	res, err := engine.Index(context.Background(), engine.Options{Root: root, StoreDir: store, Tags: tags})
	if err != nil {
		t.Fatalf("index failed: %v", err)
	}
	return res
}

// indexFixture writes files into a temp module root and indexes it.
func indexFixture(t *testing.T, files map[string]string) (*engine.Result, *index.Store, string, string) {
	t.Helper()
	offline(t)
	root := t.TempDir()
	write(t, root, files)
	store := filepath.Join(t.TempDir(), "s")
	res := indexAt(t, root, store)
	return res, index.OpenStore(store), root, store
}

func pkgFacts(t *testing.T, s *index.Store, m *index.Manifest, path string) *model.PackageFacts {
	t.Helper()
	e := m.Package(path)
	if e == nil {
		var have []string
		for _, p := range m.Packages {
			have = append(have, p.Path)
		}
		t.Fatalf("package %s not in the index; have %v", path, have)
	}
	r, err := s.OpenPackage(e)
	if err != nil {
		t.Fatal(err)
	}
	f, err := r.Facts()
	if err != nil {
		t.Fatal(err)
	}
	return f
}

func symbolNames(f *model.PackageFacts) []string {
	var out []string
	for _, s := range f.Symbols {
		out = append(out, s.Key.Name)
	}
	return out
}

func TestTypeErrorsAreRecordedNotFatal(t *testing.T) {
	res, s, _, _ := indexFixture(t, map[string]string{
		"go.mod":       "module example.com/e\n\ngo 1.24\n",
		"bad/bad.go":   "package bad\n\nfunc Ok() int { return 1 }\n\nfunc Broken() int { return undefinedName }\n\ntype T struct{}\n\nfunc (T) M() {}\n",
		"good/good.go": "package good\n\nimport \"example.com/e/bad\"\n\nfunc Use() int { return bad.Ok() }\n",
		"miss/miss.go": "package miss\n\nimport _ \"example.com/nope/missing\"\n\nfunc F() {}\n",
	})

	bad := pkgFacts(t, s, res.Manifest, "example.com/e/bad")
	if !bad.HasErrors || res.Manifest.Package("example.com/e/bad").HasErrors != true {
		t.Error("a package with a type error is not flagged has_errors")
	}
	// Exactly one diagnostic, positioned: not also the compiler's raw output.
	if len(bad.Diagnostics) != 1 || bad.Diagnostics[0].File != "bad/bad.go" || bad.Diagnostics[0].Line != 5 ||
		!strings.Contains(bad.Diagnostics[0].Msg, "undefined: undefinedName") {
		t.Errorf("diagnostics = %+v", bad.Diagnostics)
	}
	// The package is still indexed from whatever type information exists.
	for _, want := range []string{"Ok", "Broken", "T", "T.M"} {
		if !slices.Contains(symbolNames(bad), want) {
			t.Errorf("symbol %s missing from a package with errors: %v", want, symbolNames(bad))
		}
	}

	// A package that imports a broken one still indexes, and resolves its calls.
	good := pkgFacts(t, s, res.Manifest, "example.com/e/good")
	if good.HasErrors {
		t.Errorf("importer of a broken package is flagged too: %+v", good.Diagnostics)
	}
	if !slices.ContainsFunc(good.Occurrences, func(o model.Occurrence) bool {
		return o.Role == model.RoleCall && o.Symbol.Name == "Ok"
	}) {
		t.Error("call into the broken package was not resolved")
	}

	// A missing import is a positioned diagnostic.
	miss := pkgFacts(t, s, res.Manifest, "example.com/e/miss")
	if !miss.HasErrors || len(miss.Diagnostics) != 1 || miss.Diagnostics[0].Line != 3 ||
		!strings.Contains(miss.Diagnostics[0].Msg, "example.com/nope/missing") {
		t.Errorf("missing import: %+v", miss.Diagnostics)
	}
}

func TestGeneratedTestOnlyAndEmbeddedFiles(t *testing.T) {
	res, s, root, store := indexFixture(t, map[string]string{
		"go.mod":            "module example.com/h\n\ngo 1.24\n",
		"gen/gen.go":        "package gen\n\nfunc A() {}\n",
		"gen/gen_gen.go":    "// Code generated by hand. DO NOT EDIT.\n\npackage gen\n\nfunc B() {}\n",
		"only/only_test.go": "package only_test\n\nimport \"testing\"\n\nfunc TestX(t *testing.T) {}\n",
		"emb/emb.go":        "package emb\n\nimport _ \"embed\"\n\n//go:embed data.txt\nvar Data string\n",
		"emb/data.txt":      "hello\n",
	})

	gen := pkgFacts(t, s, res.Manifest, "example.com/h/gen")
	flags := map[string]bool{}
	for _, f := range gen.Files {
		flags[f.Path] = f.Generated
	}
	if flags["gen/gen.go"] || !flags["gen/gen_gen.go"] {
		t.Errorf("generated flags = %v", flags)
	}

	// A directory with only an external test file has no package of its own.
	if res.Manifest.Package("example.com/h/only") != nil {
		t.Error("indexed an empty package for a test-only directory")
	}
	only := pkgFacts(t, s, res.Manifest, "example.com/h/only_test")
	if len(only.Files) != 1 || !only.Files[0].Test {
		t.Errorf("only_test files = %+v", only.Files)
	}

	// The embedded file is part of emb's input: editing it re-indexes emb.
	write(t, root, map[string]string{"emb/data.txt": "changed\n"})
	res2 := indexAt(t, root, store)
	if !slices.Equal(res2.Reindexed, []string{"example.com/h/emb"}) {
		t.Errorf("editing an embedded file re-indexed %v", res2.Reindexed)
	}
}

func TestVendoredDependency(t *testing.T) {
	offline(t)
	root := t.TempDir()
	write(t, root, map[string]string{
		"dep/go.mod":  "module example.com/dep\n\ngo 1.24\n",
		"dep/dep.go":  "package dep\n\nfunc Hello() string { return \"hi\" }\n",
		"app/go.mod":  "module example.com/app\n\ngo 1.24\n\nrequire example.com/dep v0.0.0\n\nreplace example.com/dep => ../dep\n",
		"app/main.go": "package main\n\nimport \"example.com/dep\"\n\nfunc main() { _ = dep.Hello() }\n",
	})
	if out, err := runIn(filepath.Join(root, "app"), "go", "mod", "vendor"); err != nil {
		t.Fatalf("go mod vendor: %v\n%s", err, out)
	}
	app := filepath.Join(root, "app")
	store := filepath.Join(t.TempDir(), "s")
	res := indexAt(t, app, store)

	if len(res.Manifest.Packages) != 1 || res.Manifest.Packages[0].Path != "example.com/app" {
		t.Errorf("vendor/ must not be indexed as project code: %v", res.Manifest.Packages)
	}
	f := pkgFacts(t, index.OpenStore(store), res.Manifest, "example.com/app")
	var stub *model.External
	for i := range f.Externals {
		if f.Externals[i].Key.Name == "Hello" {
			stub = &f.Externals[i]
		}
	}
	if stub == nil || stub.Module != "example.com/dep" || stub.Version != "=> ../dep" {
		t.Errorf("stub for the vendored function = %+v", stub)
	}

	// vendor/modules.txt is part of the environment hash.
	write(t, app, map[string]string{"vendor/modules.txt": readFile(t, filepath.Join(app, "vendor", "modules.txt")) + "# touched\n"})
	if res2 := indexAt(t, app, store); len(res2.Reindexed) != 1 {
		t.Errorf("editing vendor/modules.txt re-indexed %v", res2.Reindexed)
	}
}

func TestWorkspace(t *testing.T) {
	offline(t)
	root := t.TempDir()
	write(t, root, map[string]string{
		"go.work":     "go 1.24\n\nuse (\n\t./liba\n\t./libb\n)\n",
		"liba/go.mod": "module example.com/liba\n\ngo 1.24\n",
		"liba/a.go":   "package liba\n\nfunc A() int { return 1 }\n",
		"libb/go.mod": "module example.com/libb\n\ngo 1.24\n\nrequire example.com/liba v0.0.0\n",
		"libb/b.go":   "package libb\n\nimport \"example.com/liba\"\n\nfunc B() int { return liba.A() }\n",
	})
	store := filepath.Join(t.TempDir(), "s")
	res := indexAt(t, root, store)
	var paths []string
	for _, p := range res.Manifest.Packages {
		paths = append(paths, p.Path+"@"+p.Dir)
	}
	if !slices.Equal(paths, []string{"example.com/liba@liba", "example.com/libb@libb"}) {
		t.Fatalf("workspace packages = %v", paths)
	}

	// An API change in one module reaches the module that uses it.
	write(t, root, map[string]string{"liba/a.go": "package liba\n\nfunc A() int { return 1 }\n\nfunc New() {}\n"})
	res = indexAt(t, root, store)
	if !sameSet(res.Reindexed, []string{"example.com/liba", "example.com/libb"}) {
		t.Errorf("cross-module API change re-indexed %v", res.Reindexed)
	}
	// A body change does not.
	write(t, root, map[string]string{"liba/a.go": "package liba\n\nfunc A() int { return 2 }\n\nfunc New() {}\n"})
	res = indexAt(t, root, store)
	if !slices.Equal(res.Reindexed, []string{"example.com/liba"}) {
		t.Errorf("cross-module body change re-indexed %v", res.Reindexed)
	}
	// Any workspace module's go.mod is part of the environment.
	write(t, root, map[string]string{"libb/go.mod": "module example.com/libb\n\ngo 1.24\n\nrequire example.com/liba v0.0.0\n\n// touched\n"})
	res = indexAt(t, root, store)
	if len(res.Reindexed) != 2 {
		t.Errorf("editing libb/go.mod re-indexed %v", res.Reindexed)
	}
	scratch := filepath.Join(t.TempDir(), "scratch")
	indexAt(t, root, scratch)
	compareStores(t, store, scratch)
}

func TestCgoPackage(t *testing.T) {
	if _, err := exec.LookPath("gcc"); err != nil {
		if _, err := exec.LookPath("cc"); err != nil {
			t.Skip("no C compiler")
		}
	}
	res, s, root, store := indexFixture(t, map[string]string{
		"go.mod": "module example.com/cg\n\ngo 1.24\n",
		"c/c.go": "package c\n\n/*\n#include <stdlib.h>\nstatic int add(int a, int b) { return a + b; }\n*/\nimport \"C\"\n\nfunc Add(a, b int) int { return int(C.add(C.int(a), C.int(b))) }\n\nfunc Free(p *C.char) { C.free(nil) }\n",
		"c/h.h":  "// header\n",
	})
	f := pkgFacts(t, s, res.Manifest, "example.com/cg/c")
	if f.HasErrors {
		t.Fatalf("cgo package has errors: %+v", f.Diagnostics)
	}
	// Only the real source file appears: no build-cache paths.
	if len(f.Files) != 1 || f.Files[0].Path != "c/c.go" || f.Files[0].Generated {
		t.Errorf("files = %+v", f.Files)
	}
	for _, sy := range f.Symbols {
		if strings.Contains(sy.Key.Name, "_Cgo_") || strings.Contains(sy.Key.Name, "_cgo") {
			t.Errorf("cgo internal leaked into the index: %s", sy.Key)
		}
	}
	// Positions name the original file: Add is on line 9 of c.go.
	add := findSymbol(f, "Add")
	if add == nil || add.Pos.Line != 9 || add.Pos.Col != 6 {
		t.Errorf("Add = %+v, want c.go:9:6", add)
	}
	// C.add resolves to a positionless symbol displayed as C.add.
	c := findSymbol(f, "_Cfunc_add")
	if c == nil || c.Name != "C.add" || c.Pos.Line != 0 {
		t.Errorf("C.add symbol = %+v", c)
	}
	if !slices.ContainsFunc(f.Occurrences, func(o model.Occurrence) bool {
		return o.Role == model.RoleCall && o.Symbol.Name == "_Cfunc_add" && o.Line == 9
	}) {
		t.Error("the call C.add(...) was not recorded on line 9")
	}
	// Every occurrence points into c.go, in order.
	for i, o := range f.Occurrences {
		if o.File != 0 {
			t.Errorf("occurrence %d is in file %d", i, o.File)
		}
		if i > 0 && (f.Occurrences[i-1].Line > o.Line) {
			t.Errorf("occurrences out of line order at %d", i)
		}
	}

	// Editing the C code in the comment re-indexes the package; the header
	// (a non-Go file of the package) is tracked as well.
	write(t, root, map[string]string{"c/h.h": "// changed header\n"})
	if r := indexAt(t, root, store); !slices.Equal(r.Reindexed, []string{"example.com/cg/c"}) {
		t.Errorf("editing a header re-indexed %v", r.Reindexed)
	}
	scratch := filepath.Join(t.TempDir(), "scratch")
	indexAt(t, root, scratch)
	compareStores(t, store, scratch)
}

func findSymbol(f *model.PackageFacts, name string) *model.Symbol {
	for i := range f.Symbols {
		if f.Symbols[i].Key.Name == name {
			return &f.Symbols[i]
		}
	}
	return nil
}

func runIn(dir, name string, args ...string) (string, error) {
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	out, err := runIn(filepath.Dir(path), "cat", filepath.Base(path))
	if err != nil {
		t.Fatal(err)
	}
	return out
}
